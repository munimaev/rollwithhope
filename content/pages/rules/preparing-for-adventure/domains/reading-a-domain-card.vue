Каждая карточка домена включает в себя пять элементов:</p>
<ol>
<li>
<p><strong>Уровень.</strong> Число в левом верхнем углу карточки указывает её уровень. Вы можете выбирать карточки домена только своего уровня или ниже.</p>
</li>
<li>
<p><strong>Домен.</strong> Под указанием уровня находится символ, обозначающий домен. Вы можете выбирать карточки только из доменов, принадлежащих вашему классу.</p>
</li>
<li>
<p><strong>Стоимость вызова.</strong> Число и значок молнии в правом верхнем углу карточки обозначают стоимость её вызова. Это не имеет значения при создании персонажа, но начиная с 5 уровня у вас будет больше карточек, чем доступного места на руке (на руке у вас набор из пяти активных карточек; см. раздел <a class="wikilink" href="/rules/playing-an-adventure/domain-cards">«На руке и в запасе»</a> в главе 2). Обычно вы можете переместить неактивную карточку из запаса в руку только во время привала, но вы можете получить количество Стресса, равное стоимости вызова карточки, чтобы обменять её в другое время.</p>
</li>
<li>
<p><strong>Тип.</strong> Тип карточки указан в центре над её названием. Существует три типа карточек домена: способности, заклинания и гримуары. Способности, как правило, немагические по своей природе, тогда как заклинания — магические. Гримуары уникальны для домена Кодекс и представляют собой набор мелких заклинаний, объединённых в одну карточку. Некоторые игровые механики применимы только к определённым типам карточек.</p>
</li>
<li>
<p><strong>Свойство.</strong> Текст в нижней части карточки описывает ее свойство, включая все особые правила, которые необходимо соблюдать при использовании этой карточки.</p>
</li>
</ol>
