<h6 id="управление-магией"><span class="marker" data-marker="minor"></span>Управление магией<a class="anchor" href="#управление-магией" aria-label="Ссылка на раздел"></a></h6>
<p>Ваше происхождение позволяет изменять саму суть магии. Когда вы накладываете заклинание или атакуете оружием, наносящим магический урон, вы можете <strong>получить Стресс</strong>, чтобы выбрать один из следующих эффектов:</p>
<ul>
<li>Увеличить его дистанцию на одну категорию.</li>
<li>Добавить +2 к результату броска действия.</li>
<li>Удвоить значение одной из костей урона.</li>
<li>Поразить дополнительную цель в пределах дистанции.</li>
</ul>
<h4 id="свойства-подкласса-специализация"><span class="marker" data-marker="chapter"></span>Свойства подкласса — Специализация<a class="anchor" href="#свойства-подкласса-специализация" aria-label="Ссылка на раздел"></a></h4>
<h6 id="магическая-поддержка"><span class="marker" data-marker="minor"></span>Магическая поддержка<a class="anchor" href="#магическая-поддержка" aria-label="Ссылка на раздел"></a></h6>
<p>Ваша природа позволяет вам усиливать чужие магические способности. Когда вы помогаете союзнику при броске заклинания, вы можете использовать <strong>d8</strong> в качестве кости преимущества. Один раз до конца следующего долгого отдыха, после того как вы помогли союзнику совершить бросок заклинания, вы также можете поменять местами значения, выпавшие на его костях дуализма.</p>
<h4 id="свойства-подкласса-мастерство"><span class="marker" data-marker="chapter"></span>Свойства подкласса — Мастерство<a class="anchor" href="#свойства-подкласса-мастерство" aria-label="Ссылка на раздел"></a></h4>
<h6 id="магический-заряд"><span class="marker" data-marker="minor"></span>Магический заряд<a class="anchor" href="#магический-заряд" aria-label="Ссылка на раздел"></a></h6>
<p>Вы можете накапливать магическую энергию для усиления своих способностей. Вы получаете состояние <em>Заряжен</em> после получения магического урона или если специально <strong>тратите 2 Надежды</strong>, чтобы <em>зарядиться</em>. Когда вы успешно совершаете наносящую магический урон атаку, будучи <em>Заряженным</em>, вы можете снять с себя это состояние, чтобы получить +10 к урону или добавить +3 к сложности броска Реакции цели. Вы перестаёте быть <em>Заряженным</em> после долгого отдыха.</p>
