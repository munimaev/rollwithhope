<p>Вы можете призвать выбранную стихию для защиты. При успешной атаке против вас можете <strong>получить Стресс</strong> и описать, как используете стихию для обороны. Затем бросьте <strong>d6</strong> и добавьте результат к вашему Уклонению против этой атаки.</p>
