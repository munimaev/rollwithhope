<h6 id="родство-со-стихией"><span class="marker" data-marker="minor"></span>Родство со стихией<a class="anchor" href="#родство-со-стихией" aria-label="Ссылка на раздел"></a></h6>
<p>Выберите одну из стихий при создании персонажа: воздух, земля, огонь, молния, вода.</p>
<p>Вы можете использовать эту стихию для создания безвредных эффектов. Кроме того, вы можете <strong>потратить Надежду</strong> и описать, как ваше управление стихией помогает вашему предстоящему броску действия, затем получите либо +2 к броску, либо +3 к урону.</p>
