<h6 id="сплочение"><span class="marker" data-marker="minor"></span>Сплочение<a class="anchor" href="#сплочение" aria-label="Ссылка на раздел"></a></h6>
<p>Один раз за сессию, опишите, как вы вдохновляете отряд, и дайте себе и каждому из союзников по кости Сплочения. На 1 уровне ваша кость Сплочения — <strong>d6</strong>. Персонаж игрока может потратить свою кость Сплочения, чтобы бросить её и добавить результат к своему броску действия, реакции или урона, либо снять количество Стресса, равное выпавшему значению. В конце каждой сессии всенеиспользованные кости Сплочения сбрасываются.
На 5 уровне кость Сплочения увеличивается до <strong>d8</strong>.</p>
