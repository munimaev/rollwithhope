<h6 id="исчезновение"><span class="marker" data-marker="minor"></span>Исчезновение<a class="anchor" href="#исчезновение" aria-label="Ссылка на раздел"></a></h6>
<p>В любой момент вы можете <strong>получить Стресс</strong>, чтобы скрыться <em>Под покровом</em>. Получив состояние Под покровом благодаря этому свойству, вы автоматически избавляетесь от состояния <em>Скован</em>, а также остаётесь <em>Под покровом</em> до тех пор, пока не совершите бросок со Страхом или не закончите отдых.</p>
