<h6 id="теневой-шаг"><span class="marker" data-marker="minor"></span>Теневой шаг<a class="anchor" href="#теневой-шаг" aria-label="Ссылка на раздел"></a></h6>
<p>Вы можете перемещаться между тенями. Когда вы входите в область тьмы или тени, отбрасываемой другим существом или объектом, вы можете <strong>получить Стресс</strong>, чтобы исчезнуть и появиться в любой другой тени в пределах дальней дистанции. Вы оказываетесь <em>Под покровом</em>, когда появляетесь в новой точке.</p>
<h4 id="свойства-подкласса-специализация"><span class="marker" data-marker="chapter"></span>Свойства подкласса — Специализация<a class="anchor" href="#свойства-подкласса-специализация" aria-label="Ссылка на раздел"></a></h4>
<h6 id="облако-тьмы"><span class="marker" data-marker="minor"></span>Облако тьмы<a class="anchor" href="#облако-тьмы" aria-label="Ссылка на раздел"></a></h6>
<p>Совершите <strong>бросок заклинания (15)</strong>. При успехе создайте временное облако тьмы, покрывающее область на ваш выбор в пределах средней дистанции. Находящиеся внутри него не видят наружу, а снаружи не видно внутрь. Вы считаетесь Под покровом от всех врагов, чья линия видимости перекрывается этим облаком.</p>
