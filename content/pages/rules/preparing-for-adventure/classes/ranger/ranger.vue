<h6 id="метка-следопыта"><span class="marker" data-marker="minor"></span>Метка Следопыта<a class="anchor" href="#метка-следопыта" aria-label="Ссылка на раздел"></a></h6>
<p>Потратьте Надежду и атакуйте цель. При успехе нанесите обычный урон от атаки и поставьте временную Метку на цель атаки. Пока это свойство активно (или пока вы не поставите Метку на другую цель), вы получаете следующие усиления против отмеченной цели:</p>
<ul>
<li>Вы точно знаете направление, в котором она находится.</li>
<li>Когда вы наносите ей урон, она должна получить Стресс.</li>
<li>При провале атаки по цели, вы можете снять с неё Метку, чтобы перебросить кости дуализма.</li>
</ul>
