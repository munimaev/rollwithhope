<h6 id="неудержимый"><span class="marker" data-marker="minor"></span>Неудержимый<a class="anchor" href="#неудержимый" aria-label="Ссылка на раздел"></a></h6>
<p>Один раз до конца следующего долгого отдыха вы можете стать Неудержимым. Вы получаете кость Неудержимости (на 1-м уровне — d4). Разместите её в отведённом месте на листе персонажа, начав со значения 1. После успешной атаки, нанёсшей Рану, увеличьте значение на 1. Когда значение превысит максимум для кости или сцена завершится — вы теряете состояние Неудержимый и убираете кость. На 5-м уровне размер кости увеличивается до d6.</p>
<p>Будучи Неудержимым, вы:</p>
<ul>
<li>Снижаете степень физического урона на один порог (с тяжелого до ощутимого, с ощутимого до легкого, с легкого — до нуля).</li>
<li>Добавляете текущее значение кости Неудержимости к своему броску урона.</li>
<li>Не можете быть Скованы или Уязвимы.</li>
</ul>
<blockquote>
<p>[!tip] Подсказка
Если ваша кость Неудержимости — это d4 и на ней сейчас 4, то при следующем увеличении вы убираете кость. Однако если ваша кость Неудержимости — это d6 и на ней сейчас 4, то при следующем увеличении вы переворачиваете её на 5. В этом случае вы уберёте кость, только когда потребуется увеличить её до 7.</p>
</blockquote>
