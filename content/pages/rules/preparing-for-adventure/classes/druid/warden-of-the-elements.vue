<h4 id="свойства-подкласса-основа"><span class="marker" data-marker="chapter"></span>Свойства подкласса — Основа<a class="anchor" href="#свойства-подкласса-основа" aria-label="Ссылка на раздел"></a></h4>
<h6 id="воплощение-стихии"><span class="marker" data-marker="minor"></span>Воплощение стихии<a class="anchor" href="#воплощение-стихии" aria-label="Ссылка на раздел"></a></h6>
<p><strong>Получите Стресс</strong>, чтобы стать <em>Воплощением</em> одной из стихий до получения тяжёлого урона или до конца следующего отдыха:</p>
<ul>
<li><strong>Огонь:</strong> Когда находящийся вплотную противник наносит вам урон, он получает <strong>1d10</strong> магического урона.</li>
<li><strong>Земля:</strong> Вы получаете бонус к порогам урона, равный значению сноровки.</li>
<li><strong>Вода:</strong> Когда вы наносите урон находящемуся вплотную противнику, все остальные противники в пределах ближней дистанции получают Стресс.</li>
<li><strong>Воздух:</strong> Вы можете левитировать, получая преимущество на броски Проворности.</li>
</ul>
<h4 id="свойства-подкласса-специализация"><span class="marker" data-marker="chapter"></span>Свойства подкласса — Специализация<a class="anchor" href="#свойства-подкласса-специализация" aria-label="Ссылка на раздел"></a></h4>
<h6 id="аура-стихии"><span class="marker" data-marker="minor"></span>Аура стихии<a class="anchor" href="#аура-стихии" aria-label="Ссылка на раздел"></a></h6>
<p>Один раз до конца следующего отдыха, пока вы <em>Воплощаете</em> стихию, вы можете создать соответствующую ауру, действующую в пределах средней дистанции:</p>
<ul>
<li><strong>Огонь:</strong> Каждый раз, когда противник получает хотя бы 1 Рану, он также получает Стресс.</li>
<li><strong>Земля:</strong> Ваши союзники получают +1 к Силе.</li>
<li><strong>Вода:</strong> Когда противник наносит вам урон, вы можете <strong>получить Стресс</strong>, чтобы переместить его в любую точку в пределах ближней дистанции от его изначального расположения.</li>
<li><strong>Воздух:</strong> Когда вы или союзник получаете урон от атаки из-за пределов дистанции вплотную, снизьте его на <strong>1d8</strong>.</li>
</ul>
<h4 id="свойства-подкласса-мастерство"><span class="marker" data-marker="chapter"></span>Свойства подкласса — Мастерство<a class="anchor" href="#свойства-подкласса-мастерство" aria-label="Ссылка на раздел"></a></h4>
<h6 id="владыка-стихий"><span class="marker" data-marker="minor"></span>Владыка стихий<a class="anchor" href="#владыка-стихий" aria-label="Ссылка на раздел"></a></h6>
<p>Ваша связь со стихией усиливается. <em>Воплощение</em> получает следующие дополнительные эффекты:</p>
<ul>
<li><strong>Огонь:</strong> +1 к сноровке для атак и заклинаний наносящих урон.</li>
<li><strong>Земля:</strong> Бросьте <strong>d6</strong> за каждую Рану, которую должны получить. За каждую выпавшую 6 — отмените Рану.</li>
<li><strong>Вода:</strong> Когда по вам попадает атака, вы можете <strong>получить Стресс</strong>, чтобы временно сделать атакующего <em>Уязвимым</em>.</li>
<li><strong>Воздух:</strong> Вы получаете +1 к Уклонению и можете летать.</li>
</ul>
