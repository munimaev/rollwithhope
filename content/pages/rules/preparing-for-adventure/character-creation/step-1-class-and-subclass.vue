<h4 id="лист-персонажа-и-материалы-подкласса"><span class="marker" data-marker="chapter"></span>Лист персонажа и материалы подкласса<a class="anchor" href="#лист-персонажа-и-материалы-подкласса" aria-label="Ссылка на раздел"></a></h4>
<p>Выбрав класс, возьмите соответствующий лист персонажа и краткую памятку по классу, затем определитесь с подклассом и получите его базовую карточку. Лист персонажа — рабочий документ для параметров героя, так что держите под рукой бумажную или цифровую копию. Заполняя бумажный вариант, пишите карандашом: значения будут меняться по мере роста уровня. Образец заполненного листа — в разделе «Пример персонажа». Все листы персонажей и памятки по классам можно скачать на официальном сайте Daggerheart; базовый лист персонажа также встроен в приложение игры.</p>
<h4 id="запишите-свой-уровень"><span class="marker" data-marker="chapter"></span>Запишите свой уровень<a class="anchor" href="#запишите-свой-уровень" aria-label="Ссылка на раздел"></a></h4>
<p>Персонажи в Daggerheart начинают с 1-го уровня. Укажите свой уровень в соответствующем поле в верхней части листа персонажа и не забывайте обновлять его каждый раз, когда ваш персонаж получает новый уровень. Мы рекомендуем начинать кампанию с 1-го уровня, но более опытная группа может начать с более высокого, если так предпочитает мастер и игроки.</p>
<h4 id="укажите-детали-персонажа"><span class="marker" data-marker="chapter"></span>Укажите детали персонажа<a class="anchor" href="#укажите-детали-персонажа" aria-label="Ссылка на раздел"></a></h4>
<p>На любом этапе создания персонажа вы можете вписать его имя и предпочитаемое обращение в верхней строке листа, а также заполнить раздел с описанием персонажа в руководстве. Для некоторых людей имя и внешний вид персонажа являются приоритетными, а другим требуется время, чтобы найти подходящие варианты. Главное — чтобы к моменту завершения создания персонажей у всех за столом были готовы имена и описания; а порядок выполнения этих шагов не имеет значения.</p>
<h4 id="свойства-класса"><span class="marker" data-marker="chapter"></span>Свойства класса<a class="anchor" href="#свойства-класса" aria-label="Ссылка на раздел"></a></h4>
<p>Каждый класс начинается с одним или несколькими уникальными <strong>свойствами класса</strong>. Вам не нужно записывать их вручную — они уже указаны в левом нижнем углу листа персонажа соответствующего класса. Эти свойства доступны только вашему классу. Если одно из них требует сделать выбор во время создания персонажа, примите это решение до начала первой сессии.</p>
