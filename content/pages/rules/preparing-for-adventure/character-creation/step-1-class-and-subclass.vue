<p>Первый шаг в создании персонажа — это выбор <strong>класса</strong>, за который вы хотите играть. Каждый класс — это ролевой архетип, который определяет, какие способности будут доступны вам на протяжении всей кампании. Например, вы можете выбрать стража, если хотите быть «танком» в своей группе — тем, кто бросается в бой сломя голову и защищает других ценой своей жизни. Или, может быть, вы захотите сыграть за волшебника, который использует уникальные заклинания для решения проблем, лечит союзников и применяет изощрённую боевую магию.</p>
