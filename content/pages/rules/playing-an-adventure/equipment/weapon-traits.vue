<h5 id="название"><span class="marker" data-marker="minor"></span>Название<a class="anchor" href="#название" aria-label="Ссылка на раздел"></a></h5>
<p>В начале названия оружия обычно совпадают с его типом — например, секира или рунические знаки. По мере роста персонажа и улучшения снаряжения название может стать конкретнее: «пламенный клинок из драконьей чешуи», «доблестный лук» или даже именное — «Волшебная палочка Эссека».</p>
<h5 id="атрибут"><span class="marker" data-marker="minor"></span>Атрибут<a class="anchor" href="#атрибут" aria-label="Ссылка на раздел"></a></h5>
<p>Это указывает, какой атрибут используется при атаке этим оружием. Например, оружие, в котором указан атрибут «Сила», использует атрибут «Сила» вашего персонажа каждый раз, когда он атакует с его помощью цель.</p>
<h5 id="дистанция"><span class="marker" data-marker="minor"></span>Дистанция<a class="anchor" href="#дистанция" aria-label="Ссылка на раздел"></a></h5>
<p>Дистанция обозначает максимальное расстояние, с которого оружие или эффект может поразить цель. Вы можете попасть эффектом или оружием в цель на дистанции вплотную, ближней, средней, дальней или очень дальней дистанции.</p>
<h5 id="урон"><span class="marker" data-marker="minor"></span>Урон<a class="anchor" href="#урон" aria-label="Ссылка на раздел"></a></h5>
<p>Урон отражает, насколько смертоносным является ваше оружие для противников. Когда в параметре урона оружия указан тип кости — например, «d8» — вы бросаете эту кость, чтобы определить нанесённый урон.</p>
<p>По мере повышения уровня ваш персонаж увеличивает свою сноровку, которая начинается с 1. Если не указано иное, вы бросаете количество костей урона, равное значению вашей сноровки. Например, если сноровка вашего персонажа равна 2, а кость урона — d8, вы бросаете 2d8 и складываете выпавшие значения. Если у вас выпало 4 и 8, вы наносите 12 урона.</p>
<h5 id="тип-урона"><span class="marker" data-marker="minor"></span>Тип урона<a class="anchor" href="#тип-урона" aria-label="Ссылка на раздел"></a></h5>
<p>Тип урона оружия указывает, какой вид урона оно наносит цели: физический (физ) или магический (маг). Физический урон наносят любые оружия, которые режут, колют или дробят (например, мечи, длинные луки и боевые молоты). Магический урон вызывается или усиливается магией (например, заклинаниями «Призыв роя», «Полуночный дух» и «Кара»).</p>
<p>Тип урона имеет значение, потому что некоторые существа могут иметь сопротивление или иммунитет к одному из двух типов. Например, призраки могут быть менее восприимчивы к физическому урону, чем к магическому.</p>
<p>Обычно вы не можете использовать оружие, наносящее магический урон, если у вас нет атрибута магии.</p>
<h5 id="хват"><span class="marker" data-marker="minor"></span>Хват<a class="anchor" href="#хват" aria-label="Ссылка на раздел"></a></h5>
<p>Хват оружия показывает, сколько рук требуется для его использования. Оружие бывает одноручным или двуручным. Когда вы выбираете оружие, вы также отмечаете на листе персонажа, сколько рук оно занимает в соответствии с его хватом. Если вы не можете взять какое-либо оружие, потому что ваши руки уже заняты, то вы не можете его экипировать.</p>
<p>Вы можете создать персонажа с любым количеством рук или описывать, как он использует оружие чем-то, отличным от рук. Однако для отслеживания хвата у каждого персонажа механически есть только две конечности, способные к обращению с оружием.</p>
<h5 id="свойство"><span class="marker" data-marker="minor"></span>Свойство<a class="anchor" href="#свойство" aria-label="Ссылка на раздел"></a></h5>
<p>Свойство оружия описывает особые правила, применимые только к данному оружию. Например, некоторые свойства уменьшают или увеличивают параметры персонажа, а другие дают ему особые способы нанесения урона. Свойства оружия применяются только к этому оружию; вы не можете применять его свойства к другому оружию. Ваш персонаж получает бонусы от свойства оружия только пока оно экипировано. Если вы убираете оружие в инвентарь, теряете его или избавляетесь от него, персонаж больше не получает бонусов от его свойства.</p>
<h5 id="стрелы-и-боеприпасы"><span class="marker" data-marker="minor"></span>Стрелы и боеприпасы<a class="anchor" href="#стрелы-и-боеприпасы" aria-label="Ссылка на раздел"></a></h5>
<p>Мы предполагаем, что если у вашего персонажа есть лук, то у него есть и достаточный запас обычных стрел. Если у него есть огнестрельное оружие, то у него есть и достаточный запас пуль соответствующего типа. Однако если персонаж где-то раздобыл особые боеприпасы, будьте готовы отслеживать их ограниченное количество.</p>
