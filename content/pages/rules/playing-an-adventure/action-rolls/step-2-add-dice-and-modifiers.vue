<p>Когда вы знаете, какой атрибут персонажа использовать, пришло время выяснить, применяются ли к броску другие кости или модификаторы, такие как:</p>
<p>🔸 <strong>Кости дуализма</strong>
Вы бросаете кости Надежды и Страха для каждого броска действия.</p>
<p>🔸 <strong>Преимущество или помеха</strong>
Если при броске у вас есть преимущество или помеха (см. раздел <a class="wikilink" href="/rules/playing-an-adventure/advantage-and-disadvantage">«Преимущество и помеха»</a>), отложите этот d6 для броска. Если вы бросаете с помехой, убедитесь, что ваша кость помехи имеет отдельный цвет, чтобы вы могли запомнить, какую из костей нужно вычесть из итогового результата.</p>
<p>🔸 <strong>Свойства</strong>
Некоторые свойства позволяют вам добавлять дополнительные кости к вашему броску (или позволяют другому персонажу дать вам кость). Например, бард может дать вам кость Сплочения, которую вы можете добавить к броску действия, реакции или урона по вашему выбору. Отложите их для броска.</p>
<p>🔸 <strong>Другие кости</strong>
Иногда другие эффекты (например, помощь персонажа другого игрока) могут дать вам дополнительные кости для броска.</p>
<p>Затем подсчитайте модификаторы, которые применяются к вашему броску действия, отложив соответствующее количество жетонов персонажа, чтобы помочь вам следить за ними. Модификаторы могут включать следующее:</p>
<p>🔸 <strong>Выбранный атрибут</strong>
Добавьте или вычтите модификатор того атрибута, который вы и мастер выбрали для этого броска.</p>
<p>🔸 <strong>Опыт</strong>
Если у вас есть Опыт (или несколько), который, по вашему мнению, подходит к данной ситуации, опишите, как ваш Опыт повышает шансы на успех, а затем потратьте Надежду за каждый применяемый Опыт, чтобы добавить его модификатор к броску. Мастер может попросить вас предоставить дополнительную информацию, чтобы обосновать использование этого Опыта, но окончательное решение (в пределах разумного) за вами.</p>
<p>🔸 <strong>Классовые свойства, карточки подклассов и доменов</strong>
Иногда они дают модификаторы к вашему броску, так что следите за этим.</p>
<p>🔸 <strong>Другие бонусы или штрафы</strong>
Добавьте или вычтите другие бонусы или штрафы от снаряжения, предметов и других источников.</p>
<blockquote>
<p>[!tip] Совет
Если один и тот же Опыт годится для каждого броска, мастер вправе попросить сузить его формулировку или заменить: Опыт должен отражать специализацию персонажа, а не быть бонусом ко всему подряд.</p>
</blockquote>
<h5 id="подсчёт-жетонов-персонажа"><span class="marker" data-marker="minor"></span>Подсчёт жетонов персонажа<a class="anchor" href="#подсчёт-жетонов-персонажа" aria-label="Ссылка на раздел"></a></h5>
<p>Объявив модификаторы к броску, возьмите жетоны персонажа. Жетоны — это не кости, а счётчики для подсчёта итога. Сложите все модификаторы перед броском и возьмите столько жетонов, сколько получилось.</p>
<p>Пример: –1 к Проворности и +2 от Опыта дают итоговый модификатор +1 — отложите 1 жетон.</p>
<blockquote>
<p>[!tip] Совет
При отрицательном итоговом модификаторе жетоны тоже подойдут — они значат вычитание, а не прибавление. Для наглядности используйте жетоны другого цвета.</p>
</blockquote>
