<p>В повествовании «момент» — это событие, которое меняет направление истории: сдвиг в мире, значимое действие или реакция, эмоциональное откровение или важное решение.</p>
<p>Как мастер в совместной игре, вы будете по очереди с игроками озвучивать такие моменты: вы задаёте момент, а затем даёте им возможность отреагировать и продолжить сцену своими собственными моментами. Это похоже на танец, разговор или партию в теннис.</p>
<p>Фокус на моментах очень удобен при подготовке — вместо того чтобы выписывать каждую мелкую деталь того, что случится, думайте моментами: о тех эпизодах, которые придают сцене или последовательности форму.</p>
