<p>Персонажи в городе могут вмешаться в эту последовательность в любой момент — застать переодетого наёмника при нападении или оказаться в таверне, когда наёмники пройдут к казармам и дому мэра.</p>
<p>Зная основные моменты плана, легче сохранять логику мира, пока персонажи действуют. Например, персонажи могут остановить атаку на казармы, но не помешать захвату мэра — тогда наёмники засядут в его доме с заложником, а стража обратится за помощью к героям.</p>
<p>«Думать моментами» помогает и в более крупном масштабе, и с событиями за кадром. Если партия спешит предотвратить переворот, используйте <a class="wikilink" href="/rules/running-an-adventure/core-gm-mechanics/countdowns/countdowns">счётчик прогресса</a> для расстояния до города и <a class="wikilink" href="/rules/running-an-adventure/core-gm-mechanics/countdowns/standard-countdown">стандартный счётчик</a> для этапов самого переворота, согласовывая темп обоих.</p>
<p>Например: если персонажам нужно преодолеть 500 миль (счётчик прогресса), а переворот займёт неделю (стандартный счётчик, шаг каждый день) — продвигайте счётчик прогресса и уменьшайте стандартный на 1 каждый раз, когда персонажи бросают на скорость передвижения за день.</p>
<p>Если расстояние меньше, сократите и сроки переворота — скажем, до нескольких дней с шагом счётчика раз в несколько часов. Так вы будете точно знать, что происходит, когда персонажи врываются в сцену, и не придётся импровизировать всё на ходу.</p>
