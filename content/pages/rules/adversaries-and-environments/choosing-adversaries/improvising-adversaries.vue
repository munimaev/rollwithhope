<h4 id="адаптация-к-другим-тирам"><span class="marker" data-marker="chapter"></span>Адаптация к другим тирам<a class="anchor" href="#адаптация-к-другим-тирам" aria-label="Ссылка на раздел"></a></h4>
<p>Перенося противника с 1-2 тира на 3-4, увеличьте Ран и Стресс на 1-3 ячейки в зависимости от желаемой живучести и числа завязанных на Стрессе свойств. Также скорректируйте свойства, наносящие урон помимо стандартной атаки.</p>
<p>Если уверенно придумываете свойства на лету, можно даже создать совершенно нового противника по этим параметрам. Руководство не гарантирует идеальной подгонки под вашу группу, но снижает риск, что противник окажется партии не по силам — или наоборот, падёт за пару бросков.</p>
<h4 id="добавление-или-изменение-свойств"><span class="marker" data-marker="chapter"></span>Добавление или изменение свойств<a class="anchor" href="#добавление-или-изменение-свойств" aria-label="Ссылка на раздел"></a></h4>
<p>Повышая тир противника, добавьте новое свойство, делающее его опаснее, а не просто увеличивайте урон и Сложность текущих. Снижая тир — уберите одно из самых мощных или влиятельных свойств.</p>
<h4 id="импровизация-орд-приспешников-и-одиночек"><span class="marker" data-marker="chapter"></span>Импровизация Орд, Приспешников и Одиночек<a class="anchor" href="#импровизация-орд-приспешников-и-одиночек" aria-label="Ссылка на раздел"></a></h4>
<p>Их уровни силы сильно отличаются от других противников — вот рекомендации для импровизации на лету:</p>
<p>🔸 <strong>Орда:</strong> стандартная атака наносит высокий урон, который падает примерно вдвое, когда Орда теряет половину максимума Ран.
🔸 <strong>Приспешник:</strong> фиксированный урон стандартной атаки (обычно 1-5) используйте и для свойства «Групповая атака»; значение свойства «Приспешник» (урон для поражения нескольких Приспешников одной атакой) зависит от тира — обычно 3-15.
🔸 <strong>Одиночка:</strong> высокий урон, много ячеек Ран и свойства для более частых действий («Неумолимый») или урона по области.</p>
