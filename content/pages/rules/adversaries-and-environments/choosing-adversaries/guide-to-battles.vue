<p><em>Пора создать боевое столкновение!</em></p>
<p>Раздел «Руководство по сражениям» предлагает отправную точку для создания сбалансированных столкновений. На следующих страницах подробно описаны типы противников и даны рекомендации по их созданию.</p>
<p>Это руководство поможет примерно сбалансировать столкновение, чтобы вы могли определиться с противниками и их количеством. Сначала рассчитайте стартовые очки битвы — они определят ваш бюджет на столкновение. Затем скорректируйте бюджет в зависимости от других факторов. Наконец, создайте столкновение, потратив все очки битвы на добавление противников.</p>
<p>Планируя сражение, рассчитайте количество очков битвы по формуле:
<strong>(3 × количество персонажей игроков в бою) + 2</strong></p>
<blockquote>
<p>[!example] Пример
Если в группе три персонажа, у вас будет 11 очков битвы. Если персонажей пять — 17.</p>
</blockquote>
<p>Имейте в виду, что формуле могут потребоваться изменения, когда вы будете лучше понимать уровень силы группы и их возможности.</p>
<h4 id="корректировка-очков-битвы"><span class="marker" data-marker="chapter"></span>Корректировка очков битвы<a class="anchor" href="#корректировка-очков-битвы" aria-label="Ссылка на раздел"></a></h4>
<p>Некоторые факторы увеличивают или уменьшают ваш бюджет очков битвы:</p>
<ul>
<li><strong>Вычтите 1 очко</strong>, чтобы сделать бой легче или короче.</li>
<li><strong>Вычтите 2 очка</strong>, чтобы использовать 2 Одиночек или больше.</li>
<li><strong>Вычтите 2 очка</strong>, чтобы добавить бонус +1d4 (или фиксированный бонус +2) к урону всех противников — это усложнит битву без увеличения её длительности.</li>
<li><strong>Добавьте 1 очко</strong>, если вы выбрали противника с тира ниже.</li>
<li><strong>Добавьте 1 очко</strong>, если вы не включили в битву ни Громил, ни Орд, ни Лидеров, ни Одиночек.</li>
<li><strong>Добавьте 2 очка</strong>, чтобы сделать бой опаснее или дольше.</li>
</ul>
<h4 id="трата-очков-битвы"><span class="marker" data-marker="chapter"></span>Трата очков битвы<a class="anchor" href="#трата-очков-битвы" aria-label="Ссылка на раздел"></a></h4>
<p>После подсчёта очков битвы потратьте их полностью, чтобы создать своё боевое столкновение.</p>
<ul>
<li><strong>Потратьте 1 очко</strong> за каждую группу Приспешников, равную количеству персонажей игроков.</li>
<li><strong>Потратьте 1 очко</strong> за каждого Социального противника или Поддержку.</li>
<li><strong>Потратьте 2 очка</strong> за каждую Орду, Стрелка, Рядового или Скрытного противника.</li>
<li><strong>Потратьте 3 очка</strong> за каждого Лидера.</li>
<li><strong>Потратьте 4 очка</strong> за каждого Громилу.</li>
<li><strong>Потратьте 5 очков</strong> за каждого Одиночку.</li>
</ul>
<blockquote>
<p>[!tip] Совет
Некоторых противников призывают другие свойства — их не нужно учитывать в общей сумме очков.</p>
</blockquote>
<blockquote>
<p>[!example] Пример
Игорь готовит столкновение для группы из четырёх игроков, чтобы представить новую вражескую фракцию. Четыре персонажа дают стартовый бюджет в 14 очков битвы. Он хочет сделать столкновение чуть легче и снижает бюджет до 13: тратит 8 очков на двух Громил, 4 очка на двух Рядовых и 1 очко на четырёх Приспешников.</p>
<p>Дальше группа выслеживает фракцию и натыкается на патруль у аванпоста. На этот раз Игорь тратит 10 очков на пять Рядовых, 2 очка на Стрелка и 2 очка на восьмерых Приспешников.</p>
<p>В финале, когда группа прорывается к лидеру фракции, Игорь усложняет бой: добавляет +2 ко всем броскам урона противников, что снижает бюджет до 12 очков, и тратит 3 очка на Лидера, 4 очка на Громилу, 4 очка на две Орды и 1 очко на Поддержку. Лидер также может призывать Приспешников по необходимости.</p>
</blockquote>
